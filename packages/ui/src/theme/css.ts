import type { Theme } from "./generate"

/** Tokens that aren't colours from the generator. */
const staticTokens = {
  "--bg-overlay": "rgba(16, 17, 23, 0.32)",
  "--shadow-menu":
    "0 0 0 1px rgba(16, 17, 23, 0.06), 0 4px 12px rgba(16, 17, 23, 0.08)",
  "--shadow-dialog":
    "0 0 0 1px rgba(16, 17, 23, 0.06), 0 16px 48px rgba(16, 17, 23, 0.16)",
  "--shadow-panel": "0 1px 2px rgba(16, 17, 23, 0.04)",
} as const

/** One declaration, wrapped the way Prettier wraps it past 80 columns. */
function declaration(name: string, value: string): string {
  const line = `  ${name}: ${value};`
  return line.length > 80 ? `  ${name}:\n    ${value};` : line
}

/** The :root block written to styles/tokens.css. */
export function renderTokensCss(theme: Theme): string {
  const lines = [...Object.entries(theme), ...Object.entries(staticTokens)].map(
    ([name, value]) => declaration(name, value)
  )
  return [
    "/*",
    " * Generated by packages/ui/src/theme/generate.ts. Don't edit by hand:",
    " * change the generator and run `npm run tokens -w @workspace/ui`.",
    " */",
    ":root {",
    ...lines,
    "}",
    "",
  ].join("\n")
}
